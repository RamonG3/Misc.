// Build the online referee's Edge Function: node server/build.js [--min]  ->  server/supabase/functions/duel/gen/
//
// The function runs the same rules as the page: this copies web/engine.js (with async/await taken out, as
// for the hard bot's playouts), web/cards.json, web/deckrules.js and web/referee.js into ES modules for
// Deno. Never edit server/supabase/functions/duel/gen/ by hand, and never keep a second engine.
//
// The version stamp is the first 10 hex digits of sha256(engine.js + "\n" + cards.json). The page must
// send the same stamp (build_arena.py will work it out the same way), or the server asks it to update.
//
// Card rarities (for the one-Legendary rule) come from web/arena_assets.js, which is generated on Ramon's
// PC and isn't in the repo; server/rarity.json keeps the rarities that aren't Common, and is refreshed
// here whenever arena_assets.js is present.
//
// --min shrinks the generated code with terser (npm i terser), for deploying through the Supabase connector.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const WEB = path.join(ROOT, 'web');
const OUT = path.join(__dirname, 'supabase', 'functions', 'duel', 'gen');
const MIN = process.argv.includes('--min');

const read = (f) => fs.readFileSync(path.join(WEB, f), 'utf8').replace(/\r\n/g, '\n');   // (a Windows checkout says the same)
const unwait = (src) => src.replace(/\basync\s+/g, '').replace(/\bawait\s+/g, '');   // as bot_levels.js does
const head = (from) => `// Generated by server/build.js from ${from}. Don't edit.\n`;
const wrap = (src, from) => `${head(from)}const module = { exports: {} };\n(function (window) {\n${src}\n})({});\nexport default module.exports;\n`;

async function shrink(code) {
  if (!MIN) return code;
  const { minify } = require('terser');
  const r = await minify(code, { module: true, compress: { passes: 2 }, mangle: true, format: { preamble: code.split('\n')[0] } });
  return r.code + '\n';
}

(async () => {
  const engine = read('engine.js');
  const cardsText = read('cards.json');
  const version = crypto.createHash('sha256').update(engine).update('\n').update(cardsText).digest('hex').slice(0, 10);
  const cards = JSON.parse(cardsText);

  const rarityFile = path.join(__dirname, 'rarity.json');
  const assets = path.join(WEB, 'arena_assets.js');
  if (fs.existsSync(assets)) {
    const a = fs.readFileSync(assets, 'utf8');
    const set1 = JSON.parse(a.slice(a.indexOf('=') + 1).trim().replace(/;\s*$/, '')).set1;
    const rare = {};
    for (const n of Object.keys(set1).sort()) if (set1[n].rarity !== 'C') rare[n] = set1[n].rarity;
    const text = JSON.stringify(rare, null, 1) + '\n';
    if (!fs.existsSync(rarityFile) || fs.readFileSync(rarityFile, 'utf8') !== text) {
      fs.writeFileSync(rarityFile, text);
      console.log('server/rarity.json updated from web/arena_assets.js');
    }
  }
  const rare = JSON.parse(fs.readFileSync(rarityFile, 'utf8'));
  const set1 = Object.fromEntries(Object.entries(rare).map(([n, r]) => [n, { rarity: r }]));

  // The fingerprint: the card data, the rarities and one fixed duel played through the referee. The function
  // works it out again from its own copy (index.js, op hello -> intact).
  const S = (() => { const m = { exports: {} }; new Function('module', 'window', unwait(engine))(m, {}); return m.exports; })();
  S.setData(cards);
  const F = require(path.join(WEB, 'referee.js')).make(S, require(path.join(WEB, 'deckrules.js')).make(S.CARDS, set1));
  const st = cards.decks.filter((d) => d.group === 'Starter decks');
  const fixture = { seed: 20261115, decks: [st[0].cards, st[1].cards], capes: [st[0].capes[0], st[1].capes[0]], names: ['Ann', 'Bo'] };
  const serverData = { cards: cards.cards, capes: cards.capes, decks: [] };
  const fingerprint = crypto.createHash('sha256').update(JSON.stringify(serverData)).update(JSON.stringify(set1))
    .update(JSON.stringify(F.selfPlay(fixture))).digest('hex').slice(0, 16);

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  const files = {
    'engine.js': await shrink(wrap(unwait(engine), 'web/engine.js (async/await taken out)')),
    'cards.js': `${head('web/cards.json')}export default ${JSON.stringify(serverData)};\n`,
    'rarity.js': `${head('server/rarity.json')}export default ${JSON.stringify(set1)};\n`,
    'deckrules.js': await shrink(wrap(read('deckrules.js'), 'web/deckrules.js')),
    'referee.js': await shrink(wrap(read('referee.js'), 'web/referee.js')),
    'version.js': `${head('web/engine.js + web/cards.json')}export const VERSION = '${version}';\n` +
      `export const FINGERPRINT = '${fingerprint}';\nexport const FIXTURE = ${JSON.stringify(fixture)};\n`,
  };
  let total = 0;
  for (const [f, text] of Object.entries(files)) { fs.writeFileSync(path.join(OUT, f), text); total += text.length; }
  console.log(`server/supabase/functions/duel/gen: ${Object.keys(files).length} files, ${Math.round(total / 1024)} KB, version ${version}, fingerprint ${fingerprint}`);
})().catch((e) => { console.error(e); process.exit(1); });
